"""095 — Semantic plaintext prior: a strong LOCAL LLM as the tie-break among the
crib-consistent decryptions that 092/093 showed n-grams cannot separate.

exp 092/093 established that at K4's required complexity (k~4 hand-crafted
alphabets) the ciphertext + cribs admit MANY decryptions reaching real-English
HEXAGRAM statistics ({k=4:10, k=5:21} distinct), and letter-statistics cannot
single out THE plaintext. The reframed question (Knight/decipherment lineage):
is any crib-consistent, statistically-English decryption SEMANTICALLY meaningful?
A hexagram model can't tell; a real language model can.

This runs a strong local instruct model (gemma4:31b-it via ollama, $0 -- the
machine has 128 GB) as a semantic JUDGE: score 0-100 whether a string is a
meaningful, grammatical English message. We CALIBRATE it on real-English and
random controls (it must separate them, else it's untrustworthy), then score the
pool of crib-consistent high-hexagram decryptions generated by the 093 hillclimb.

Outcomes: a candidate scoring high = a SEMANTICALLY coherent crib-consistent
decryption = a genuine lead to verify. All candidates scoring low = the strongest
possible confirmation of 092/093: even a 31B LLM finds no meaning in any
crib-consistent decryption, so K4 is under-determined at the SEMANTIC level too
and pure decipherment (cipher + language prior) is insufficient without a further
constraint.

$0, local, pure decipherment. No paid API. Output:
experiments/results/<date>_095_semantic_llm_prior.jsonl
"""

from __future__ import annotations

import importlib.util
import json
import math
import random
import re
import statistics
import time
import urllib.request
from datetime import date
from pathlib import Path

import _kpa
from _verdict import Verdict, write_verdict
from kryptos.constants import K4
from kryptos.cribs import CRIBS
from kryptos.utils import clean

e035 = importlib.util.module_from_spec(importlib.util.spec_from_file_location(
    "e035", str(Path(__file__).parent / "035_minimum_alphabet_analysis.py")))
e035.__spec__.loader.exec_module(e035)

N = 97
ALPHA = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
MODEL = "gemma4:31b-it-q8_0"
OLLAMA = "http://localhost:11434/api/chat"

CRIB_TRIPLES = []
for c in CRIBS:
    for off, (p, ch) in enumerate(zip(c.plaintext, c.ciphertext)):
        CRIB_TRIPLES.append((c.start - 1 + off, p, ch))
CRIB_POS = {pos for pos, _, _ in CRIB_TRIPLES}
FREE_POS = [i for i in range(N) if i not in CRIB_POS]


# ---------------------------------------------------------------- LLM judge
def llm_score(text, model=MODEL, retries=2):
    sys = ("You rate whether a string of letters (ignore spacing/case) is a MEANINGFUL, "
           "grammatical English message. Reply ONLY with JSON: {\"score\": N, \"reason\": \"...\"} "
           "where N is 0 (random letters) to 100 (fluent meaningful English).")
    body = {"model": model, "messages": [{"role": "system", "content": sys},
                                         {"role": "user", "content": text}],
            "stream": False, "think": False, "options": {"num_predict": 120, "temperature": 0}}
    for _ in range(retries + 1):
        try:
            req = urllib.request.Request(OLLAMA, data=json.dumps(body).encode(),
                                         headers={"Content-Type": "application/json"})
            r = json.loads(urllib.request.urlopen(req, timeout=240).read())
            c = re.sub(r"<think>.*?</think>", "", r.get("message", {}).get("content", ""), flags=re.S)
            m = re.search(r'"score"\s*:\s*(\d+)', c)
            if m:
                rs = re.search(r'"reason"\s*:\s*"([^"]*)"', c)
                return int(m.group(1)), (rs.group(1)[:80] if rs else "")
        except Exception as e:
            last = str(e)[:60]
    return None, "parse/conn fail"


# ---------------------------------------------------------------- candidate pool (093 hillclimb)
def random_completion(pins, rng):
    dec = dict(pins)
    used = set(dec.values())
    fc = [ch for ch in ALPHA if ch not in dec]
    fp = [p for p in ALPHA if p not in used]
    rng.shuffle(fp)
    for ch, p in zip(fc, fp):
        dec[ch] = p
    return dec, fc


def gen_candidates(rng, eng_bar, ks=(4, 5), restarts=24, steps=4000, want=18):
    cribs = e035.build_crib_constraints()
    pos_of_node = [c[0] for c in cribs]
    edges = set()
    for i in range(len(cribs)):
        for j in range(i + 1, len(cribs)):
            if e035.cribs_conflict(cribs[i], cribs[j]):
                edges.add((i, j))
    pool = {}
    for K in ks:
        coloring = e035.find_k_coloring(len(cribs), edges, max(K, 3))
        crib_color = {pos_of_node[n]: coloring[n] % K for n in range(len(cribs))}
        pins = {c: {} for c in range(K)}
        for pos, p, ch in CRIB_TRIPLES:
            pins[crib_color[pos]][ch] = p

        def decrypt(selfree, decmaps):
            return "".join(decmaps[crib_color[i] if i in CRIB_POS else selfree[i]][K4[i]] for i in range(N))

        for _ in range(restarts):
            decmaps, fe = {}, {}
            for c in range(K):
                d, f = random_completion(pins[c], rng)
                decmaps[c], fe[c] = d, f
            selfree = {i: rng.randrange(K) for i in FREE_POS}
            cur = _kpa.score_free_text(decrypt(selfree, decmaps))
            for s in range(steps):
                T = 0.5 * (0.01 / 0.5) ** (s / steps)
                if rng.random() < 0.5:
                    i = rng.choice(FREE_POS); old = selfree[i]; nw = rng.randrange(K)
                    if nw == old:
                        continue
                    selfree[i] = nw
                    cand = _kpa.score_free_text(decrypt(selfree, decmaps))
                    if cand >= cur or rng.random() < math.exp((cand - cur) / max(T, 1e-6)):
                        cur = cand
                    else:
                        selfree[i] = old
                else:
                    c = rng.randrange(K)
                    if len(fe[c]) < 2:
                        continue
                    a, b = rng.sample(fe[c], 2)
                    decmaps[c][a], decmaps[c][b] = decmaps[c][b], decmaps[c][a]
                    cand = _kpa.score_free_text(decrypt(selfree, decmaps))
                    if cand >= cur or rng.random() < math.exp((cand - cur) / max(T, 1e-6)):
                        cur = cand
                    else:
                        decmaps[c][a], decmaps[c][b] = decmaps[c][b], decmaps[c][a]
            pt = decrypt(selfree, decmaps); sc = _kpa.score_free_text(pt)
            if sc >= eng_bar and pt not in pool:
                pool[pt] = (round(sc, 2), K)
    return sorted(pool.items(), key=lambda kv: -kv[1][0])[:want]


def main() -> int:
    out = _kpa.RESULTS / f"{date.today()}_095_semantic_llm_prior.jsonl"
    rng = random.Random(0)
    t0 = time.perf_counter()

    corp = clean((_kpa.REPO / "data" / "corpora" / "buchan_39steps.txt").read_text())
    rr = random.Random(7)
    es = sorted(_kpa.score_free_text(corp[(s := rr.randrange(len(corp) - N)):s + N]) for _ in range(300))
    eng_bar = es[int(0.05 * len(es))]

    candidates = gen_candidates(rng, eng_bar)

    # calibration + control set
    eng_ctrl = [corp[(s := rr.randrange(len(corp) - N)):s + N] for _ in range(5)]
    gib_ctrl = ["".join(chr(65 + rr.randrange(26)) for _ in range(N)) for _ in range(4)]
    items = ([("english", t, None) for t in eng_ctrl]
             + [("gibberish", t, None) for t in gib_ctrl]
             + [("k4_candidate", pt, meta) for pt, meta in candidates])

    scored = []
    with open(out, "w") as f:
        for kind, txt, meta in items:
            sc, reason = llm_score(txt)
            rec = {"kind": kind, "llm_score": sc, "reason": reason, "hexagram": meta,
                   "text": txt if kind != "english" else txt[:40] + "..."}
            scored.append(rec)
            f.write(json.dumps(rec) + "\n")

    def avg(kind):
        v = [r["llm_score"] for r in scored if r["kind"] == kind and r["llm_score"] is not None]
        return round(statistics.mean(v), 1) if v else None
    eng_m, gib_m = avg("english"), avg("gibberish")
    cand_scores = [(r["llm_score"], r["text"]) for r in scored
                   if r["kind"] == "k4_candidate" and r["llm_score"] is not None]
    cand_max = max((s for s, _ in cand_scores), default=None)
    cand_mean = round(statistics.mean([s for s, _ in cand_scores]), 1) if cand_scores else None
    best_cand = max(cand_scores, key=lambda x: x[0]) if cand_scores else (None, None)

    elapsed = time.perf_counter() - t0
    # calibration gate: the judge must separate English from gibberish
    calibrated = (eng_m is not None and gib_m is not None and eng_m - gib_m >= 40 and eng_m >= 60)
    # a real lead requires a candidate the LLM rates clearly meaningful AND near English level
    lead = calibrated and cand_max is not None and cand_max >= 60 and (cand_max >= eng_m - 20)
    status = "promising" if lead else ("inconclusive" if calibrated else "inconclusive")

    insights = [
        f"Local LLM judge ({MODEL}, $0). Calibration: real-English mean {eng_m}, random-gibberish mean {gib_m} "
        f"(separation {None if (eng_m is None or gib_m is None) else round(eng_m-gib_m,1)}) -> judge "
        f"trustworthy = {calibrated}.",
        f"Scored {len(cand_scores)} distinct crib-consistent high-hexagram decryptions (from the 093 hillclimb "
        f"at k=4,5, all >= the real-English hexagram bar {eng_bar:.2f}). LLM semantic scores: max {cand_max}, "
        f"mean {cand_mean}. Best candidate ({best_cand[0]}): {best_cand[1]}",
        (f"SEMANTIC LEAD: a crib-consistent decryption scores {cand_max} (near English) -- inspect & verify; "
         f"this would be the first semantically-coherent K4 candidate." if lead else
         f"NO SEMANTIC SIGNAL: every crib-consistent, hexagram-English decryption is rated meaningless by a 31B "
         f"LLM (max {cand_max} vs English ~{eng_m}). This is the strongest confirmation of 092/093 -- K4 is "
         f"under-determined at the SEMANTIC level, not just statistically. Cipher + language prior (n-gram OR "
         f"LLM) cannot single out THE plaintext; a further, non-linguistic constraint is required."),
    ]

    write_verdict(out, Verdict(
        exp="095", title="semantic LLM plaintext prior (re-rank of crib-consistent decryptions)",
        hypothesis="a strong language model can identify a semantically-meaningful plaintext among the "
                   "crib-consistent, hexagram-English decryptions n-grams cannot separate",
        status=status, best_score=None,
        best_partial=f"judge calibrated={calibrated} (Eng {eng_m}/Gib {gib_m}); {len(cand_scores)} candidates "
                     f"scored, max {cand_max}, mean {cand_mean}",
        search_space=len(items), elapsed_s=round(elapsed, 1),
        insights=insights,
        next_steps=(["verify the high-scoring candidate byte-exact against the cribs; cross-check with a second "
                     "local model (qwen3.5:27b) to rule out judge bias"] if lead else
                    ["semantic prior confirms under-determination: no crib-consistent decryption is meaningful "
                     "even to a 31B LLM. Remaining levers: MaxSAT for a cleaner global optimum (exp 096, same "
                     "bound), or write up the bounded/under-determined negative -- not more search"]),
        metrics={"model": MODEL, "calibrated": calibrated, "english_mean": eng_m, "gibberish_mean": gib_m,
                 "candidate_max": cand_max, "candidate_mean": cand_mean, "n_candidates": len(cand_scores)}),
    )
    print(f"\njudge calibrated={calibrated} (Eng {eng_m}/Gib {gib_m}); {len(cand_scores)} candidates, "
          f"max {cand_max}, mean {cand_mean}; status={status}. -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
